#!/usr/bin/env python3
"""
Interactive script to generate .env file for AI Sycophancy Lab.

Usage:
    python setup_env.py
    python setup_env.py --provider deepseek --api-key sk-xxxxxxxx
    python setup_env.py --provider mock
"""

import os
import sys
import argparse
from pathlib import Path
from typing import Optional


def get_user_input(prompt: str, default: str = "") -> str:
    """Get user input with default value."""
    if default:
        user_input = input(f"{prompt} [{default}]: ").strip()
        return user_input if user_input else default
    else:
        return input(f"{prompt}: ").strip()


def check_api_key(provider: str, api_key: Optional[str] = None) -> Optional[str]:
    """Validate API key for the selected provider."""
    if provider == "mock":
        return None
    
    if api_key:
        return api_key
    
    print(f"\n⚠️  {provider.upper()} provider requires an API key.")
    print(f"Please obtain your API key from:")
    
    if provider == "deepseek":
        print(f"  - Website: https://www.deepseek.com/")
        print(f"  - Navigate to API management page")
        print(f"  - Create or copy your API key\n")
    elif provider == "openai":
        print(f"  - Website: https://platform.openai.com/")
        print(f"  - Navigate to API keys page")
        print(f"  - Create or copy your API key\n")
    
    while True:
        api_key = input(f"Enter your {provider.upper()} API key (or 'skip' to use mock mode): ").strip()
        if api_key.lower() == 'skip':
            return None
        elif api_key:
            return api_key
        else:
            print("❌ API key cannot be empty. Please try again or enter 'skip'.")


def generate_env_content(provider: str, api_key: Optional[str] = None, **kwargs) -> str:
    """Generate .env file content."""
    
    # If API key is not provided for real provider, fall back to mock
    if provider != "mock" and not api_key:
        print("\n⚠️  No API key provided. Falling back to mock mode.")
        provider = "mock"
    
    content = f"""# AI Sycophancy Lab - Environment Configuration
# Generated by setup_env.py

# Application Settings
APP_NAME=AI Sycophancy Lab
APP_VERSION=1.0.0
DEBUG=false

# API Settings
API_PREFIX=/api

# CORS Settings (comma-separated origins)
CORS_ORIGINS=["http://localhost:3000", "http://127.0.0.1:3000"]

# Database Settings
DATABASE_URL=sqlite+aiosqlite:///./data/sycophancy_lab.db

# LLM Settings
# Current provider: {provider}
LLM_PROVIDER={provider}
"""
    
    # Add provider-specific configuration
    if provider == "deepseek":
        content += f"""
# DeepSeek Settings
DEEPSEEK_API_KEY={api_key}
DEEPSEEK_MODEL={kwargs.get('model', 'deepseek-chat')}
DEEPSEEK_TEMPERATURE={kwargs.get('temperature', 0.3)}
DEEPSEEK_MAX_TOKENS={kwargs.get('max_tokens', 500)}
DEEPSEEK_TIMEOUT={kwargs.get('timeout', 30)}
DEEPSEEK_BASE_URL=https://api.deepseek.com/v1
"""
    elif provider == "openai":
        content += f"""
# OpenAI Settings
OPENAI_API_KEY={api_key}
OPENAI_MODEL={kwargs.get('model', 'gpt-3.5-turbo')}
OPENAI_TEMPERATURE={kwargs.get('temperature', 0.3)}
OPENAI_MAX_TOKENS={kwargs.get('max_tokens', 500)}
OPENAI_TIMEOUT={kwargs.get('timeout', 30)}
"""
    else:  # mock
        content += """
# Mock Mode
# No additional configuration needed for mock mode
"""
    
    # Add common settings
    content += f"""
# Research Settings
STUDY_ID={kwargs.get('study_id', 'study4_pilot')}
EXPERIMENT_MODE={kwargs.get('experiment_mode', 'development')}

# Logging Settings
STORE_MESSAGE_TEXT={kwargs.get('store_message_text', 'true')}
REDACT_DIRECT_IDENTIFIERS={kwargs.get('redact_direct_identifiers', 'true')}
INCLUDE_PROMPT_VERSION={kwargs.get('include_prompt_version', 'true')}
INCLUDE_CONFIG_HASH={kwargs.get('include_config_hash', 'true')}
"""
    
    return content


def save_env_file(content: str, directory: Path, force: bool = False) -> Path:
    """Save .env file to the specified directory."""
    env_path = directory / ".env"
    
    if env_path.exists() and not force:
        overwrite = input(f"\n⚠️  .env file already exists at {env_path}\nOverwrite? (y/N): ").strip().lower()
        if overwrite != 'y':
            print("❌ Operation cancelled.")
            sys.exit(0)
    
    env_path.write_text(content, encoding='utf-8')
    return env_path


def interactive_setup() -> tuple[str, Optional[str], dict]:
    """Run interactive setup to get configuration from user."""
    print("\n" + "=" * 60)
    print("AI Sycophancy Lab - Environment Setup")
    print("=" * 60)
    
    # Select provider
    print("\nSelect LLM Provider:")
    print("  1. Mock Mode (default, no API key needed)")
    print("  2. DeepSeek (real LLM, requires API key)")
    print("  3. OpenAI (real LLM, requires API key)")
    
    while True:
        choice = input("\nEnter choice (1-3) [1]: ").strip()
        if choice == "" or choice == "1":
            provider = "mock"
            break
        elif choice == "2":
            provider = "deepseek"
            break
        elif choice == "3":
            provider = "openai"
            break
        else:
            print("❌ Invalid choice. Please enter 1, 2, or 3.")
    
    # Get API key if needed
    api_key = None
    if provider != "mock":
        api_key = check_api_key(provider)
        if not api_key:
            provider = "mock"
            print("✅ Switched to mock mode (no API key provided)")
    
    # Get additional settings
    print("\n--- Additional Settings (press Enter to use defaults) ---")
    
    settings = {
        'model': get_user_input("Model name", "deepseek-chat" if provider == "deepseek" else "gpt-3.5-turbo"),
        'temperature': get_user_input("Temperature", "0.3"),
        'max_tokens': get_user_input("Max output tokens", "500"),
        'timeout': get_user_input("Request timeout (seconds)", "30"),
        'study_id': get_user_input("Study ID", "study4_pilot"),
        'experiment_mode': get_user_input("Experiment mode", "development"),
    }
    
    return provider, api_key, settings


def main():
    """Main entry point."""
    parser = argparse.ArgumentParser(
        description="Generate .env file for AI Sycophancy Lab",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Interactive mode
  python setup_env.py
  
  # Quick setup with DeepSeek
  python setup_env.py --provider deepseek --api-key sk-xxxxxxxx
  
  # Quick setup with mock mode
  python setup_env.py --provider mock
  
  # Setup for backend directory
  python setup_env.py --output backend
        """
    )
    
    parser.add_argument(
        '--provider',
        choices=['mock', 'deepseek', 'openai'],
        help='LLM provider to use'
    )
    parser.add_argument(
        '--api-key',
        help='API key for the selected provider'
    )
    parser.add_argument(
        '--output',
        type=str,
        default='backend',
        help='Output directory for .env file (default: backend)'
    )
    parser.add_argument(
        '--force',
        action='store_true',
        help='Overwrite existing .env file without asking'
    )
    parser.add_argument(
        '--model',
        default='deepseek-chat',
        help='Model name to use'
    )
    parser.add_argument(
        '--temperature',
        type=float,
        default=0.3,
        help='Temperature for generation'
    )
    parser.add_argument(
        '--max-tokens',
        type=int,
        default=500,
        help='Maximum output tokens'
    )
    parser.add_argument(
        '--timeout',
        type=int,
        default=30,
        help='Request timeout in seconds'
    )
    
    args = parser.parse_args()
    
    # Determine mode
    if args.provider:
        # Non-interactive mode
        provider = args.provider
        api_key = args.api_key
        
        if provider != "mock" and not api_key:
            print(f"⚠️  Warning: {provider.upper()} provider requires an API key.")
            api_key = check_api_key(provider, api_key)
            
            if not api_key:
                print("✅ Falling back to mock mode.")
                provider = "mock"
        
        settings = {
            'model': args.model,
            'temperature': args.temperature,
            'max_tokens': args.max_tokens,
            'timeout': args.timeout,
            'study_id': 'study4_pilot',
            'experiment_mode': 'development',
        }
    else:
        # Interactive mode
        provider, api_key, settings = interactive_setup()
    
    # Generate content
    content = generate_env_content(provider, api_key, **settings)
    
    # Determine output directory
    output_dir = Path(args.output)
    if not output_dir.is_absolute():
        output_dir = Path(__file__).parent / output_dir
    
    if not output_dir.exists():
        print(f"❌ Output directory does not exist: {output_dir}")
        sys.exit(1)
    
    # Save file
    env_path = save_env_file(content, output_dir, force=args.force)
    
    print("\n" + "=" * 60)
    print("✅ .env file generated successfully!")
    print("=" * 60)
    print(f"\nLocation: {env_path}")
    print(f"Provider: {provider.upper()}")
    
    if provider == "deepseek":
        print(f"API Key: {api_key[:10]}...{api_key[-4:]}")
        print(f"Model: {settings['model']}")
    
    print("\nNext steps:")
    print("1. Review the .env file to ensure settings are correct")
    print("2. Start the backend server:")
    print(f"   cd {args.output}")
    print("   python -m uvicorn app.main:app --reload")
    print("\n3. Start the frontend server:")
    print("   cd frontend")
    print("   npm run dev")
    print("\n4. Open http://localhost:3001 in your browser")
    print("=" * 60)


if __name__ == "__main__":
    main()
